def list_scenario_summaries() -> List[ScenarioSummaryItem]:
    """Return summary items for all available scenarios."""
    return [
        ScenarioSummaryItem(
            scenario_id=s.scenario_id,
            name=s.name,
            description=s.description,
            severity=s.severity,
            zone_count=s.zone_count,
            hotspot_count=s.hotspot_count,
            highest_risk_score=s.highest_risk_score,
            highest_risk_zone_name=s.highest_risk_zone_name,
            critical_infrastructure_count=s.critical_infrastructure_count,
            data_label=s.data_label,
        )
        for s in SCENARIOS_STORE.values()
    ]


def get_scenario_by_id(scenario_id: str) -> ScenarioDetail | None:
    """Retrieve detailed scenario object or None."""
    return SCENARIOS_STORE.get(scenario_id)
